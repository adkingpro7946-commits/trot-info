import { PrismaClient } from '@prisma/client';
const prisma = new PrismaClient();
const NOW = new Date('2026-07-25T00:00:00+09:00');
const REVIEW = new Date('2027-01-25T00:00:00+09:00');
const D = (s: string) => new Date(s);
const idOf = async (slug: string) => (await prisma.artist.findUnique({ where: { slug }, select: { id: true } }))?.id ?? null;

type Src = { title: string; publisher: string; url: string };

async function upsertAlbum(a: {
  slug: string; title: string; artistSlug: string; type: string; releaseDate: string;
  tracks: string[]; description: string; sources: Src[];
}) {
  const aid = await idOf(a.artistSlug);
  await prisma.music.upsert({ where: { slug: a.slug }, update: {}, create: { slug: a.slug, title: a.title, status: 'draft' } });
  const m = await prisma.music.update({
    where: { slug: a.slug },
    data: {
      title: a.title, type: a.type, releaseDate: D(a.releaseDate), trackList: JSON.stringify(a.tracks),
      description: a.description, isSample: false, status: 'published', artists: { set: aid ? [{ id: aid }] : [] },
    },
  });
  await prisma.source.deleteMany({ where: { musicId: m.id } });
  for (const s of a.sources) {
    await prisma.source.create({ data: { musicId: m.id, sourceTitle: s.title, sourcePublisher: s.publisher, sourceUrl: s.url, sourceGrade: 'B', factType: 'release', verificationStatus: 'cross_checked', accessedAt: NOW } });
  }
}

async function upsertArticle(slug: string, a: {
  type: string; title: string; seoTitle: string; description: string; excerpt: string;
  primaryKeyword: string; body: string; sources: { t: string; p: string; u: string }[];
}) {
  const admin = await prisma.user.findFirst({ where: { role: 'admin' }, orderBy: { createdAt: 'asc' } });
  await prisma.article.upsert({ where: { slug }, update: {}, create: { slug, type: a.type, title: a.title, description: a.description, body: a.body, status: 'draft' } });
  const art = await prisma.article.update({
    where: { slug },
    data: {
      type: a.type, title: a.title, seoTitle: a.seoTitle, description: a.description, excerpt: a.excerpt,
      primaryKeyword: a.primaryKeyword, body: a.body, status: 'published', index: true, riskLevel: 'low',
      isSample: false, autoGenerated: false, publishedAt: NOW, lastFactCheckedAt: NOW, nextReviewAt: REVIEW,
      authorId: admin?.id ?? null,
    },
  });
  await prisma.source.deleteMany({ where: { articleId: art.id } });
  await prisma.source.createMany({ data: a.sources.map((s) => ({ articleId: art.id, sourceTitle: s.t, sourcePublisher: s.p, sourceUrl: s.u, sourceGrade: 'B', factType: 'reference', verificationStatus: 'cross_checked', accessedAt: NOW })) });
}

