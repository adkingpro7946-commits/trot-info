import { PrismaClient } from '@prisma/client';
const prisma = new PrismaClient();
const NOW = new Date('2026-07-25T00:00:00+09:00');
const REVIEW = new Date('2027-01-25T00:00:00+09:00');

type Src = { t: string; p: string; u: string; g?: string };

async function upsertArticle(slug: string, a: {
  type: string; title: string; seoTitle: string; description: string; excerpt: string;
  primaryKeyword: string; body: string; sources: Src[];
}) {
  const admin = await prisma.user.findFirst({ where: { role: 'admin' }, orderBy: { createdAt: 'asc' } });
  await prisma.article.upsert({ where: { slug }, update: {}, create: { slug, type: a.type, title: a.title, description: a.description, body: a.body, status: 'draft' } });
  const art = await prisma.article.update({
    where: { slug },
    data: {
      type: a.type, title: a.title, seoTitle: a.seoTitle, description: a.description, excerpt: a.excerpt,
      primaryKeyword: a.primaryKeyword, body: a.body, status: 'published', index: true, riskLevel: 'low',
      isSample: false, autoGenerated: false, publishedAt: NOW, lastFactCheckedAt: NOW, nextReviewAt: REVIEW,
      authorId: admin?.id ?? null,
    },
  });
  await prisma.source.deleteMany({ where: { articleId: art.id } });
  await prisma.source.createMany({ data: a.sources.map((s) => ({ articleId: art.id, sourceTitle: s.t, sourcePublisher: s.p, sourceUrl: s.u, sourceGrade: s.g ?? 'B', factType: 'reference', verificationStatus: 'cross_checked', accessedAt: NOW })) });
}

